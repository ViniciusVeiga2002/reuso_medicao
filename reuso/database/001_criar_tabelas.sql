begin;

create table if not exists departamento (
    id bigint generated by default as identity primary key,
    nome varchar(100) not null unique,
    criado_em timestamptz not null default now()
);

create table if not exists cargo (
    id bigint generated by default as identity primary key,
    titulo varchar(100) not null,
    nivel varchar(50),
    criado_em timestamptz not null default now(),
    unique (titulo, nivel)
);

create table if not exists jornada (
    id bigint generated by default as identity primary key,
    tipo_vinculo varchar(50) not null,
    turno varchar(50) not null,
    carga_horaria smallint not null check (carga_horaria between 1 and 168),
    criado_em timestamptz not null default now()
);

create table if not exists equipe (
    id bigint generated by default as identity primary key,
    nome varchar(100) not null,
    departamento_id bigint not null references departamento(id) on delete restrict,
    criado_em timestamptz not null default now(),
    unique (departamento_id, nome)
);

create table if not exists funcionario (
    id bigint generated by default as identity primary key,
    nome varchar(150) not null,
    matricula varchar(30) not null unique,
    email varchar(150) unique,
    telefone varchar(30),
    cpf varchar(14) unique,
    data_nascimento date,
    data_admissao date not null default current_date,
    status varchar(20) not null default 'ativo'
        check (status in ('ativo', 'inativo', 'ferias', 'afastado')),
    cargo_id bigint references cargo(id) on delete set null,
    equipe_id bigint references equipe(id) on delete set null,
    jornada_id bigint references jornada(id) on delete set null,
    superior_id bigint references funcionario(id) on delete set null,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    check (superior_id is null or superior_id <> id)
);

alter table equipe
    add column if not exists lider_id bigint references funcionario(id) on delete set null;

create table if not exists atribuicao (
    id bigint generated by default as identity primary key,
    funcionario_id bigint references funcionario(id) on delete set null,
    titulo varchar(150) not null,
    descricao text,
    status varchar(30) not null default 'aberta'
        check (status in ('aberta', 'em_andamento', 'em_validacao', 'concluida', 'cancelada')),
    prioridade varchar(20) not null default 'media'
        check (prioridade in ('baixa', 'media', 'alta', 'urgente')),
    prazo timestamptz,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create index if not exists idx_equipe_departamento on equipe(departamento_id);
create index if not exists idx_funcionario_cargo on funcionario(cargo_id);
create index if not exists idx_funcionario_equipe on funcionario(equipe_id);
create index if not exists idx_funcionario_jornada on funcionario(jornada_id);
create index if not exists idx_funcionario_superior on funcionario(superior_id);
create index if not exists idx_atribuicao_funcionario on atribuicao(funcionario_id);
create index if not exists idx_atribuicao_status on atribuicao(status);

alter table departamento enable row level security;
alter table cargo enable row level security;
alter table jornada enable row level security;
alter table equipe enable row level security;
alter table funcionario enable row level security;
alter table atribuicao enable row level security;

commit;
